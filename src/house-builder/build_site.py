"""Build the live page /house-builder/ from the design file project/Main.dc.html."""
import re, json
s = open('/home/claude/builder/project/Main.dc.html', encoding='utf-8').read()
def rep(a, b, n=None):
    global s
    c = s.count(a)
    assert c and (n is None or c == n), (c, a[:80])
    s = s.replace(a, b)
rep('<div style="width: 390px; min-height: 2700px;', '<div style="width: 100%; max-width: 430px; margin: 0 auto;', 1)
s = re.sub(r'\n  <header style=.*?</header>\n', '\n', s, count=1, flags=re.S)
rep('<div style="position: sticky; top: 0; z-index: 5;', '<div style="position: sticky; top: var(--wd-head, 0px); z-index: 5;', 1)
rep('<div role="img" aria-label="{{ sceneLabel }}" style="position: relative; width: 358px; height: 260px">',
    '<div class="scene" role="img" aria-label="{{ sceneLabel }}" style="position: relative; width: 358px; height: 260px; margin: 0 auto">', 1)
rep(' Coming soon in this prototype.', ' Coming soon.', 2)
rep('Prototype with illustrative numbers; prices to buy are indicative and still to be checked.', 'Rough estimates for a typical home, not advice. Prices to buy are indicative ranges.', 1)
style = re.search(r'<helmet>(.*?)</helmet>', s, re.S).group(1)
body = re.search(r'</helmet>(.*)</x-dc>', s, re.S).group(1)
code = re.search(r'data-dc-script[^>]*>(.*?)</script>', s, re.S).group(1)
# analytics hooks (Vercel Web Analytics custom events; ignored if not available)
code = code.replace("goStep2: function () { self.setState(", "goStep2: function () { track('step2', {}); self.setState(", 1)
code = code.replace("toggleData: function () { self.setState(", "toggleData: function () { if (!s.showData) track('own_data_click', { type: type }); self.setState(", 1)
code = code.replace("function setPlan(patch) {", "function setPlan(patch) { track('try_change', { what: Object.keys(patch).join(',') });", 1)
assert code.count("track(") == 3

frag = '''<!-- builder:start (generated by build_site.py from the design file; edit there) -->
<section id="builder" aria-label="Build your home and see your bill" style="padding: 8px 0 24px">
<style>
#builder button{-webkit-tap-highlight-color:transparent}
#builder h1{font-family:inherit}
%STYLE%
</style>
<div id="wd-root"></div>
<noscript><p style="padding:20px">The house builder needs JavaScript. The quick check below works without it.</p></noscript>
<template id="wd-tpl">%BODY%</template>
<script>
(function () {
function track(name, data) { try { window.va && window.va('event', { name: name, data: data }); } catch (e) {} }
class DCLogic { constructor(p) { this.props = p; } setState(p) { Object.assign(this.state, p); render(); } }
%CODE%
var comp = new Component({});
function get(expr, sc) { expr = expr.trim(); if (expr === 'true') return true; if (expr === 'false') return false; if (/^\\d+$/.test(expr)) return +expr;
  var v = sc; for (var p of expr.split('.')) { if (v == null) return undefined; v = v[p]; } return v; }
function interp(str, sc) { return str.replace(/\\{\\{(.*?)\\}\\}/g, function (m, e) { var v = get(e, sc); return v == null ? '' : String(v); }); }
function proc(node, sc) {
  for (var ch of Array.from(node.childNodes)) {
    if (ch.nodeType === 3) { if (ch.nodeValue.indexOf('{{') >= 0) ch.nodeValue = interp(ch.nodeValue, sc); continue; }
    if (ch.nodeType !== 1) continue;
    var tag = ch.tagName.toLowerCase();
    if (tag === 'sc-for') {
      var list = get(ch.getAttribute('list').replace(/[{}]/g, ''), sc) || [], as = ch.getAttribute('as'), frag = document.createDocumentFragment();
      list.forEach(function (it) { var w = document.createElement('div'); for (var c of ch.childNodes) w.appendChild(c.cloneNode(true));
        var s2 = Object.create(sc); s2[as] = it; proc(w, s2); while (w.firstChild) frag.appendChild(w.firstChild); });
      ch.replaceWith(frag); continue;
    }
    if (tag === 'sc-if') {
      if (get(ch.getAttribute('value').replace(/[{}]/g, ''), sc)) { proc(ch, sc); var f = document.createDocumentFragment(); while (ch.firstChild) f.appendChild(ch.firstChild); ch.replaceWith(f); }
      else ch.remove();
      continue;
    }
    for (var a of Array.from(ch.attributes)) {
      if (a.value.indexOf('{{') < 0) continue;
      if (a.name.indexOf('on') === 0) { var fn = get(a.value.replace(/[{}]/g, ''), sc); ch.removeAttribute(a.name); if (typeof fn === 'function') ch.addEventListener(a.name.slice(2), (function (f) { return function () { f(); }; })(fn)); }
      else ch.setAttribute(a.name, interp(a.value, sc));
    }
    proc(ch, sc);
  }
}
function fit() {
  var z = Math.min(1, (window.innerWidth - 32) / 358);
  document.querySelectorAll('#builder .scene').forEach(function (el) { el.style.zoom = z < 1 ? String(z) : ''; });
  var h = document.querySelector('.header'); document.getElementById('builder').style.setProperty('--wd-head', (h ? h.offsetHeight : 0) + 'px');
}
function render() {
  var root = document.getElementById('wd-root'), w = document.createElement('div');
  w.appendChild(document.getElementById('wd-tpl').content.cloneNode(true));
  proc(w, comp.renderVals()); root.replaceChildren.apply(root, Array.from(w.childNodes)); fit();
}
window.addEventListener('resize', fit);
render();
})();
</script>
</section>
<!-- builder:end -->'''
out = frag.replace('%STYLE%', style.replace('<style>', '').replace('</style>', '').replace('body{margin:0}', '')).replace('%BODY%', body).replace('%CODE%', code)
idx = '/home/claude/wattsterdam/index.html'
page = open(idx, encoding='utf-8').read()
a, z = page.index('<!-- builder:start'), page.index('<!-- builder:end -->') + len('<!-- builder:end -->')
page = page[:a] + out + page[z:]
open(idx, 'w', encoding='utf-8').write(page)
print('ok', len(out))
